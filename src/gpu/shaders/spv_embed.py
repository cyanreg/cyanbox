"""Embeds a SPIR-V binary as a C array: rx_<name>_spv[] and rx_<name>_spv_size.

The array is bytes aligned to four, which is what VkShaderModuleCreateInfo
wants from pCode; the size is in bytes."""
import sys


def main():
    spv_path, out_path, name = sys.argv[1], sys.argv[2], sys.argv[3]
    with open(spv_path, "rb") as f:
        data = f.read()
    if len(data) % 4 or data[:4] != b"\x03\x02\x23\x07":
        sys.exit(f"{spv_path}: not little-endian SPIR-V")
    with open(out_path, "w") as f:
        f.write("/* Generated by spv_embed.py from %s, do not edit. */\n" % spv_path.split("/")[-1])
        f.write("#include <stddef.h>\n#include <stdint.h>\n")
        f.write(f"static const uint8_t rx_{name}_spv[] __attribute__((aligned(4))) = {{\n")
        for i in range(0, len(data), 16):
            f.write("    " + ",".join(str(b) for b in data[i:i + 16]) + ",\n")
        f.write("};\n")
        f.write(f"static const size_t rx_{name}_spv_size = {len(data)};\n")


if __name__ == "__main__":
    main()

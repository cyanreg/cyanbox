# Writes src/common/kanji_readings.h, one reading per kanji for
# rx_utf8_latin1 (src/common/latin1.c) to fall back on when MeCab has none,
# from Unicode's Unihan_Readings.txt (in Unihan.zip of the Unicode
# Character Database): the first on'yomi (kJapaneseOn), skipping the
# historical spellings with KUW/GUW when there is another, else the first
# kun'yomi (kJapaneseKun, verb endings and all: Unihan does not mark them);
# 乃 and 之 as the "no" they are in names. Lowercase ASCII.
#
# usage: gen_kanji_readings.py Unihan_Readings.txt > src/common/kanji_readings.h

import sys

OVERRIDES = {0x4E43: 'no', 0x4E4B: 'no'}


def pick(on, kun):
    if on:
        plain = [r for r in on if 'KUW' not in r and 'GUW' not in r]
        return (plain or on)[0].lower()
    return kun[0].lower() if kun else None


def main():
    on, kun, version = {}, {}, ''
    with open(sys.argv[1], encoding='utf-8') as f:
        for line in f:
            if line.startswith('# Unicode Version'):
                version = line.split()[-1]
            if line.startswith('#') or not line.strip():
                continue
            cp, field, value = line.rstrip('\n').split('\t')
            c = int(cp[2:], 16)
            if field == 'kJapaneseOn':
                on[c] = value.split()
            elif field == 'kJapaneseKun':
                kun[c] = value.split()
    readings = {}
    for c in sorted(set(on) | set(kun)):
        r = OVERRIDES.get(c) or pick(on.get(c), kun.get(c))
        if r and r.isascii() and r.isalpha():
            readings[c] = r
    pool, at = [], {}
    for r in sorted(set(readings.values())):
        at[r] = sum(len(p) + 1 for p in pool)
        pool.append(r)
    out = sys.stdout
    out.write('/* Copyright © 2026, Lynne. BSD-2-Clause, see LICENSE.md. */\n')
    out.write('/* One reading per kanji (latin1.c), generated by tools/gen_kanji_readings.py\n')
    out.write(' * from the Unihan database of Unicode %s (Unihan_Readings.txt:\n' % version)
    out.write(' * kJapaneseOn, kJapaneseKun). That data is © Unicode, Inc., under the\n')
    out.write(' * Unicode License v3, in third_party/unicode/LICENSE. */\n\n')
    out.write('#define NB_KANJI_READINGS %d\n\n' % len(readings))
    out.write('/* The kanji, ascending. */\n')
    out.write('static const uint32_t kanji_cp[NB_KANJI_READINGS] = {\n')
    cps = list(readings)
    for i in range(0, len(cps), 10):
        out.write('    ' + ' '.join('0x%X,' % c for c in cps[i:i + 10]) + '\n')
    out.write('};\n\n')
    out.write('/* Each one\'s reading: its offset in kanji_pool. */\n')
    out.write('static const uint16_t kanji_reading[NB_KANJI_READINGS] = {\n')
    for i in range(0, len(cps), 14):
        out.write('    ' + ' '.join('%d,' % at[readings[c]] for c in cps[i:i + 14]) + '\n')
    out.write('};\n\n')
    out.write('/* The readings, each NUL-terminated. */\n')
    out.write('static const char kanji_pool[] =\n')
    line = '    "'
    for r in pool:
        piece = r + '\\0'
        if len(line) + len(piece) > 96:
            out.write(line + '"\n')
            line = '    "'
        line += piece
    out.write(line + '";\n')
    assert max(at.values()) < 65536


main()
